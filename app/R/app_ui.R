build_app_ui <- function(project, initial_month, asset_url) {
  fluidPage(
  lang = "en-AU",
  tags$head(
    tags$title("Melbourne Attractions Map"),
    tags$meta(name = "viewport", content = "width=device-width, initial-scale=1"),
    # Local app assets; Tableau Public is allowed only for the detail review embed.
    tags$meta(`http-equiv` = "Content-Security-Policy", content = paste(
      "default-src 'self' data: blob:; script-src 'self' 'unsafe-inline' 'unsafe-eval' https://public.tableau.com https://api.mapbox.com;",
      "style-src 'self' 'unsafe-inline' https://api.mapbox.com; img-src 'self' data: blob: https://api.mapbox.com https://*.tiles.mapbox.com; font-src 'self' data:;",
      "connect-src 'self' ws://127.0.0.1:* ws://localhost:* https://api.mapbox.com https://*.tiles.mapbox.com https://events.mapbox.com; worker-src 'self' blob:; frame-src https://public.tableau.com;"
    )),
    tags$link(rel = "stylesheet", href = asset_url("style.css")),
    tags$link(rel = "stylesheet", href = asset_url("detail.css")),
    tags$script(src = asset_url("app.js"), defer = "defer"),
    tags$script(src = asset_url("mapbox_main.js"), defer = "defer"),
    tags$script(src = asset_url("heatmap_interface.js"), defer = "defer"),
    tags$script(src = asset_url("full_bus_routes.js"), defer = "defer"),
    tags$script(src = asset_url("attraction_reviews.js"), defer = "defer")
  ),
  do.call(tabsetPanel, c(list(id = "page", type = "hidden",
    tabPanel(title = "Map", value = "map",
      div(class = "workspace",
        div(class = "map-column",
        uiOutput("weather_banner", class = "weather-banner", `aria-live` = "polite"),
        tags$details(class = "map-interaction-hint map-guidance", open = "open",
          tags$summary("Map tips & data notes",
            tags$span(class = "map-guidance-show", "Show"),
            tags$span(class = "map-guidance-hide", "Hide")),
          div(class = "map-guidance-body",
            tags$p("Click an attraction icon to see nearby public transport stops. Click a route at a stop to view it on the map."),
            tags$p(class = "map-data-note",
              "The heatmap shows estimates based on 2024–2025 pedestrian data. ",
              "Attraction crowd levels are estimated using pedestrian data from surrounding streets."))),
        extra_page_links_ui(),
        div(class = "map-stage",
          mapgl::mapboxglOutput("map", width = "100%", height = "100%"),
          div(class = "heatmap-toggle",
              title = "Relative street heat adjusted for footway width. Low activity fades into the map; higher activity has warmer colours. The colour scale stays fixed across all filters and hours.",
              checkboxInput("show_sensor_heat", "Crowd heatmap", value = TRUE)),
          tags$button(type = "button", class = "panel-toggle time-expand",
            `data-panel-toggle` = "time", `aria-controls` = "time_panel",
            `aria-expanded` = "true", `aria-label` = "Expand time panel", hidden = "hidden",
            "Show time"),
          tags$button(type = "button", class = "panel-toggle explore-expand",
            `data-panel-toggle` = "explore", `aria-controls` = "explore_panel",
            `aria-expanded` = "true", `aria-label` = "Expand attractions and transport panel", hidden = "hidden",
            "Show attractions / transport"),
          div(id = "time_panel", class = "time-panel",
            onchange = "if(event.isTrusted){var key=event.target.id==='selected_month'?'month':event.target.name==='weather_filter'?'weather':event.target.name==='day_type'?'day_type':null;if(key)Shiny.setInputValue('map_filter_intent',{field:key,value:event.target.value},{priority:'event'});}",
            div(class = "time-panel-heading",
              tags$p(class = "eyebrow", "MELBOURNE TIME"),
              tags$button(type = "button", class = "panel-toggle time-collapse",
                `data-panel-toggle` = "time", `aria-controls` = "time_panel",
                `aria-expanded` = "true", `aria-label` = "Collapse time panel", "Hide")),
            uiOutput("clock"),
            selectInput("selected_month", "Month",
              choices = stats::setNames(project$months, unname(project$month_labels)),
              selected = initial_month, selectize = FALSE, width = "100%"),
            radioButtons("weather_filter", "Weather",
              choices = c("Good weather" = "good_weather", "Bad weather" = "bad_weather"),
              selected = "good_weather", inline = TRUE, width = "100%"),
            radioButtons("day_type", "Day type",
              choices = c("Holiday" = "holiday", "Weekdays" = "weekdays"),
              selected = "weekdays", inline = TRUE, width = "100%"),
            div(class = "slider-heading", tags$label(`for` = "hour_slider", "Hour"),
                textOutput("hour_caption", inline = TRUE)),
            tags$input(id = "hour_slider", class = "hour-slider", type = "range",
                       min = "0", max = "23", step = "1", value = "0",
                       `aria-label` = "Select hour of day, 0 to 23", `aria-valuetext` = "00:00"),
            div(class = "hour-ticks", tags$span("00"), tags$span("06"),
                tags$span("12"), tags$span("18"), tags$span("23")),
            div(class = "play-buttons",
              actionButton("play_day", label = "▶ Play",
                           class = "play-primary")
            ),
            div(class = "speed-row",
              tags$label(`for` = "speed", "Speed"),
              selectInput("speed", NULL, choices = c("Slow · 2 s / hour" = 2,
                          "Normal · 1.2 s / hour" = 1.2, "Fast · 0.5 s / hour" = 0.5),
                          selected = 1.2, selectize = FALSE, width = "168px")
            ),
            textOutput("playback_status", container = function(...) tags$p(class = "playback-status", ...))
          )
        )
        ),
        tags$aside(id = "explore_panel", class = "attractions-panel",
          tags$button(type = "button", class = "panel-toggle explore-collapse",
            `data-panel-toggle` = "explore", `aria-controls` = "explore_panel",
            `aria-expanded` = "true", `aria-label` = "Collapse attractions and transport panel", "Hide"),
          div(id = "stop_inspector", class = "stop-inspector", hidden = "hidden"),
          tabsetPanel(id = "explore_tab", type = "pills",
          tabPanel("Attractions · 13", value = "attractions",
          div(class = "list-heading", tags$p(class = "eyebrow", "EXPLORE THE CITY"),
              div(class = "list-title", tags$h2("All attractions"), tags$span("13"))),
          uiOutput("attraction_list", class = "attraction-list")
          ),
          tabPanel("Transport", value = "transport",
            div(class = "transport-panel",
              tags$p(class = "eyebrow", "STOPS & ROUTES"),
              uiOutput("selected_context"),
              checkboxInput("show_all_transport", "Show all stops", value = FALSE),
              selectInput("nearby_radius", "Nearby radius",
                choices = c("300 m" = 300, "500 m" = 500, "1000 m" = 1000),
                selected = 300, selectize = FALSE),
              textOutput("nearby_status", container = function(...) tags$p(class = "nearby-status", ...)),
              div(class = "transport-mode-key",
                tags$span(tags$img(src = "transport/tram.svg", alt = ""), "Tram"),
                tags$span(tags$img(src = "transport/bus.svg", alt = ""), "Bus"),
                tags$span(tags$img(src = "transport/rail.svg", alt = ""), "Rail")),
              checkboxGroupInput("transport_modes", "Transport modes",
                choices = c("Tram" = "tram", "Bus" = "bus", "Rail" = "rail"),
                selected = c("tram", "bus", "rail")),
              div(id = "transport_route_controls_home",
                div(id = "transport_route_controls", class = "transport-route-controls",
                  selectInput("transport_route", "Route",
                    choices = c("No selected route" = ""), selected = "", selectize = FALSE),
                  uiOutput("transport_direction_ui"),
                  actionButton("reset_transport", "Clear route", class = "transport-reset")))
            )
          ))
        )
      )
    ),
    tabPanel(title = "Attraction details", value = "detail",
      div(class = "detail-shell",
        uiOutput("detail_page"),
        # Keep this host outside renderUI so changing attractions retains the viz.
        tags$section(id = "attraction-reviews", class = "attraction-reviews",
          `aria-label` = "Monthly visitor reviews", `aria-busy` = "false",
          `data-allowed-ids` = paste(project$attractions$attraction_id, collapse = ","),
          div(id = "reviews-message", role = "status", `aria-live` = "polite",
            tags$span(id = "reviews-status", "Select an attraction to see reviews."),
            div(id = "reviews-recovery", hidden = "hidden",
              tags$button(id = "reviews-retry", type = "button", "Retry"),
              tags$a(id = "reviews-external", target = "_blank", rel = "noopener noreferrer",
                "Open review chart"))),
          div(class = "reviews-scroll",
            div(class = "reviews-stage", div(id = "reviews-viz-host")))
        ),
        div(class = "detail-content detail-source-footer",
          tags$details(class = "detail-data-methods", tags$summary("Data & methods"),
            uiOutput(NS("attraction_detail")("sources"))))
      ))
  ), extra_page_tabs()))
)

}
